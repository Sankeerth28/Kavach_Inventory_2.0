import { existsSync } from 'node:fs';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';

/**
 * Private document storage for uploaded invoices and challans (PRD §25.2, ARCHITECTURE §7.6).
 * Used by the api (upload, authenticated download) and the worker (read for extraction).
 * Files are never public: clients receive them only through the API, after its permission checks.
 *
 * Drivers:
 * - `s3`: any S3-compatible bucket (MinIO locally). The deployment default.
 * - `local`: a directory on disk, for development machines and tests without MinIO.
 */
export interface DocumentStorage {
  readonly driver: 'local' | 's3';
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Removing a missing object is not an error. */
  delete(key: string): Promise<void>;
}

export class StorageObjectNotFound extends Error {
  constructor(key: string) {
    super(`Stored document not found: ${key}`);
    this.name = 'StorageObjectNotFound';
  }
}

/** Keys are generated by the server. This still refuses anything that could leave the root. */
const KEY_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*(\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

function assertKey(key: string): void {
  if (!KEY_RE.test(key) || key.includes('..') || key.length > 400) {
    throw new Error('Invalid storage key');
  }
}

/** projects/{projectId}/invoices/{invoiceId}/{pageNo}.{ext} */
export function invoicePageKey(
  projectId: string,
  invoiceId: string,
  pageNo: number,
  mimeType: string,
): string {
  const ext = mimeType === 'application/pdf' ? 'pdf' : mimeType === 'image/png' ? 'png' : 'jpg';
  return `projects/${projectId}/invoices/${invoiceId}/${pageNo}.${ext}`;
}

export class LocalStorage implements DocumentStorage {
  readonly driver = 'local' as const;
  private readonly root: string;

  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private resolve(key: string): string {
    assertKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  async put(key: string, body: Buffer): Promise<void> {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, body);
  }

  async get(key: string): Promise<Buffer> {
    try {
      return await readFile(this.resolve(key));
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') throw new StorageObjectNotFound(key);
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

export interface S3Options {
  bucket: string;
  region: string;
  endpoint?: string;
  accessKeyId?: string;
  secretAccessKey?: string;
  forcePathStyle?: boolean;
}

export class S3Storage implements DocumentStorage {
  readonly driver = 's3' as const;
  private readonly client: S3Client;

  constructor(private readonly options: S3Options) {
    this.client = new S3Client({
      region: options.region,
      endpoint: options.endpoint || undefined,
      forcePathStyle: options.forcePathStyle ?? false,
      credentials:
        options.accessKeyId && options.secretAccessKey
          ? { accessKeyId: options.accessKeyId, secretAccessKey: options.secretAccessKey }
          : undefined,
    });
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    assertKey(key);
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.options.bucket,
        Key: key,
        Body: body,
        ContentType: contentType,
        ServerSideEncryption: this.options.endpoint ? undefined : 'AES256',
      }),
    );
  }

  async get(key: string): Promise<Buffer> {
    assertKey(key);
    try {
      const res = await this.client.send(
        new GetObjectCommand({ Bucket: this.options.bucket, Key: key }),
      );
      if (!res.Body) throw new StorageObjectNotFound(key);
      return Buffer.from(await res.Body.transformToByteArray());
    } catch (e) {
      const name = (e as { name?: string }).name;
      if (name === 'NoSuchKey' || name === 'NotFound') throw new StorageObjectNotFound(key);
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    assertKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.options.bucket, Key: key }));
  }
}

/** The repository root: the nearest parent that holds pnpm-workspace.yaml. Falls back to cwd. */
function workspaceRoot(from = process.cwd()): string {
  let dir = path.resolve(from);
  for (let i = 0; i < 8; i += 1) {
    if (existsSync(path.join(dir, 'pnpm-workspace.yaml'))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return path.resolve(from);
}

/**
 * Builds the storage from the environment.
 * STORAGE_DRIVER = `local` (default outside production) or `s3` (default in production).
 * Local files go to STORAGE_LOCAL_DIR, or `.local/documents` at the repository root, so the api
 * and the worker see the same directory whatever their working directory is.
 */
export function createStorage(env: NodeJS.ProcessEnv = process.env): DocumentStorage {
  const driver = env.STORAGE_DRIVER ?? (env.NODE_ENV === 'production' ? 's3' : 'local');
  if (driver === 'local') {
    const dir = env.STORAGE_LOCAL_DIR
      ? path.resolve(workspaceRoot(), env.STORAGE_LOCAL_DIR)
      : path.join(workspaceRoot(), '.local', 'documents');
    return new LocalStorage(dir);
  }
  if (driver !== 's3') throw new Error(`Unknown STORAGE_DRIVER "${driver}". Use "local" or "s3".`);
  if (!env.S3_BUCKET) throw new Error('S3_BUCKET must be set when STORAGE_DRIVER=s3.');
  return new S3Storage({
    bucket: env.S3_BUCKET,
    region: env.S3_REGION ?? 'us-east-1',
    endpoint: env.S3_ENDPOINT,
    accessKeyId: env.S3_ACCESS_KEY_ID,
    secretAccessKey: env.S3_SECRET_ACCESS_KEY,
    forcePathStyle: env.S3_FORCE_PATH_STYLE === 'true',
  });
}
